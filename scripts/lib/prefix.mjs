/**
 * Copies the shared PHP packages into one product and rewrites their
 * namespace and text domain to the product's own.
 *
 * Example: `UltraMax\UI\Button` becomes `UltraMax\Core\Lib\UI\Button`
 * inside ultra-max-core, and the "ultra-max-ui" text domain becomes
 * "ultra-max-core".
 */
import fs from 'node:fs';
import path from 'node:path';
import { root } from './run.mjs';
import { phpPackages } from './products.mjs';

/**
 * Lists PHP files below a folder.
 *
 * @param {string} dir Absolute folder.
 * @return {string[]} Absolute file paths.
 */
function phpFiles( dir ) {
	if ( ! fs.existsSync( dir ) ) {
		return [];
	}
	return fs
		.readdirSync( dir, { recursive: true, withFileTypes: true } )
		.filter( ( entry ) => entry.isFile() && entry.name.endsWith( '.php' ) )
		.map( ( entry ) => path.join( entry.parentPath, entry.name ) );
}

/**
 * Rewrites shared namespaces and text domains for one product.
 *
 * @param {string} source    PHP source.
 * @param {string} namespace Product root namespace, such as "UltraMax\\Core".
 * @param {string} domain    Product text domain.
 * @return {string} Rewritten source.
 */
export function rewrite( source, namespace, domain ) {
	const names = phpPackages.map( ( pkg ) => pkg.name ).join( '|' );
	let out = source.replace(
		new RegExp( `(\\\\?)UltraMax\\\\(${ names })\\b`, 'g' ),
		( match, lead, name ) => `${ lead }${ namespace }\\Lib\\${ name }`
	);
	// Only the text domain argument of gettext calls, which always comes last:
	// __( 'Close', 'ultra-max-ui' ). Other strings, such as asset handles, stay.
	for ( const pkg of phpPackages ) {
		out = out.replace( new RegExp( `(,\\s*)'${ pkg.domain }'(\\s*\\))`, 'g' ), `$1'${ domain }'$2` );
	}
	return out;
}

/**
 * Writes the prefixed copy of every shared package into a product.
 *
 * @param {import('./products.mjs').Product} product Product.
 * @param {string} market License module to include: "dev", "rtl-theme" or "zhaket".
 * @param {string} [targetRoot] Product folder to write into; defaults to the product's source folder.
 */
export function prefixPackages( product, market = 'dev', targetRoot = path.join( root, product.dir ) ) {
	const out = path.join( targetRoot, 'vendor-prefixed' );
	fs.rmSync( out, { recursive: true, force: true } );

	for ( const pkg of phpPackages ) {
		const sources = [ ...pkg.sources ];
		if ( pkg.name === 'License' ) {
			sources.push( `packages/license/markets/${ market }` );
		}
		for ( const source of sources ) {
			const base = path.join( root, source );
			for ( const file of phpFiles( base ) ) {
				const relative = path.relative( base, file );
				const dest = path.join( out, pkg.target, path.basename( source ) === 'src' ? '' : path.basename( source ), relative );
				fs.mkdirSync( path.dirname( dest ), { recursive: true } );
				const header = '<?php\n// Generated by scripts/lib/prefix.mjs from ' + path.posix.join( source, relative.split( path.sep ).join( '/' ) ) + '. Do not edit.\n';
				const body = rewrite( fs.readFileSync( file, 'utf8' ), product.namespace, product.slug ).replace( /^<\?php\n/, '' );
				fs.writeFileSync( dest, header + body );
			}
		}
	}
}
