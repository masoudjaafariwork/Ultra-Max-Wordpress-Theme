/**
 * Writes Tailwind's own reset (preflight) limited to `.um-scope`, so it
 * resets only regions our products render and never the markup of other
 * plugins or of the WordPress admin.
 *
 * `html` and `:host` become the scope element itself; every other selector
 * applies inside the scope and, where valid, to the scope element too.
 * Wrapping in `:where()` keeps the original specificity.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import postcss from 'postcss';
import { root } from './run.mjs';

const SCOPE = ':where(.um-scope)';

/**
 * Scopes one simple selector.
 *
 * @param {string} selector Selector without commas.
 * @return {string[]} Scoped selectors.
 */
export function scopeSelector( selector ) {
	const s = selector.trim();
	if ( s === 'html' || s === ':host' || s === 'body' ) {
		return [ SCOPE ];
	}
	const scoped = [ `${ SCOPE } ${ s }` ];
	if ( ! s.includes( '::' ) && ! s.includes( ' ' ) ) {
		scoped.push( `${ s }${ SCOPE }` );
	}
	return scoped;
}

/**
 * Builds the scoped reset.
 *
 * @return {string} Output file path.
 */
export function writeScopedPreflight() {
	const require = createRequire( import.meta.url );
	const source = require.resolve( 'tailwindcss/preflight.css' );
	const css = postcss.parse( fs.readFileSync( source, 'utf8' ) );
	css.walkRules( ( rule ) => {
		if ( rule.parent?.type === 'atrule' && /keyframes/.test( rule.parent.name ) ) {
			return;
		}
		rule.selectors = rule.selectors.flatMap( scopeSelector );
	} );
	const out = path.join( root, 'build', 'generated', 'preflight.css' );
	fs.mkdirSync( path.dirname( out ), { recursive: true } );
	fs.writeFileSync( out, '/* Generated by scripts/lib/scoped-preflight.mjs from tailwindcss/preflight.css. */\n' + css.toString() );
	return out;
}
